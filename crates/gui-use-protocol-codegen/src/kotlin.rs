use gui_use_protocol::{EVENTS, METHODS, SERVICE};

use crate::types::kotlin_type;

pub fn camel(ident: &str) -> String {
    let mut parts = ident.split('_');
    let mut out = parts.next().unwrap_or_default().to_string();
    for part in parts {
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            out.extend(first.to_uppercase());
            out.push_str(chars.as_str());
        }
    }
    out
}

fn kdoc(docs: &str, indent: &str) -> String {
    let body = docs
        .lines()
        .map(|line| {
            if line.is_empty() {
                format!("{indent} *\n")
            } else {
                format!("{indent} * {}\n", line.replace("*/", "* /"))
            }
        })
        .collect::<String>();
    format!("{indent}/**\n{body}{indent} */\n")
}

pub fn generate() -> String {
    let mut out = String::from(concat!(
        "// Generated by gui-use-protocol-codegen. Do not edit by hand.\n",
        "package dev.azurice.guiuse.protocol\n\n",
        "import kotlinx.serialization.json.Json\n",
        "import kotlinx.serialization.json.JsonElement\n",
        "import kotlinx.serialization.json.JsonObject\n",
        "import kotlinx.serialization.json.buildJsonObject\n",
        "import kotlinx.serialization.json.decodeFromJsonElement\n",
        "import kotlinx.serialization.json.encodeToJsonElement\n",
        "import kotlinx.serialization.json.put\n",
        "import kotlinx.serialization.json.putJsonObject\n\n",
    ));
    out.push_str("object Methods {\n");
    for method in METHODS {
        out.push_str(&format!(
            "    const val {} = \"{}\"\n",
            method.ident.to_uppercase(),
            method.name
        ));
    }
    out.push_str("}\n\n");
    out.push_str(&kdoc(SERVICE.docs, ""));
    out.push_str(&format!("interface {} {{\n", SERVICE.name));
    for method in METHODS {
        let mut docs = method.docs.to_string();
        for arg in method.args {
            if !arg.docs.is_empty() {
                docs.push_str(&format!("\n@param {} {}", camel(arg.name), arg.docs));
            }
        }
        out.push_str(&kdoc(&docs, "    "));
        let args = method
            .args
            .iter()
            .map(|arg| {
                let ty = kotlin_type(arg.rust_type);
                let default = if ty.ends_with('?') { " = null" } else { "" };
                format!("{}: {ty}{default}", camel(arg.name))
            })
            .collect::<Vec<_>>()
            .join(", ");
        out.push_str(&format!(
            "    suspend fun {}({args}): {}\n\n",
            camel(method.ident),
            kotlin_type(method.result)
        ));
    }
    out.push_str("}\n\nobject ProtocolDispatch {\n");
    out.push_str(&format!(
        "    suspend fun dispatch(method: String, params: JsonElement, json: Json, device: {}): JsonElement =\n",
        SERVICE.name,
    ));
    out.push_str("        when (method) {\n");
    for method in METHODS {
        out.push_str(&format!(
            "            Methods.{} -> {{\n",
            method.ident.to_uppercase()
        ));
        let binding = if method.args.is_empty() {
            ""
        } else {
            "val decoded = "
        };
        out.push_str(&format!(
            "                {binding}json.decodeFromJsonElement<{}>(params)\n",
            method.params
        ));
        let args = method
            .args
            .iter()
            .map(|arg| format!("decoded.{}", arg.name))
            .collect::<Vec<_>>()
            .join(", ");
        out.push_str(&format!(
            "                json.encodeToJsonElement(device.{}({args}))\n",
            camel(method.ident)
        ));
        out.push_str("            }\n");
    }
    out.push_str("            else -> throw IllegalArgumentException(\"unknown method: $method\")\n        }\n}\n\n");
    out.push_str("object ProtocolEvents {\n");
    for event in EVENTS {
        out.push_str(&kdoc(event.docs.trim(), "    "));
        let mut chars = event.ident.chars();
        let name = chars
            .next()
            .expect("event identifier")
            .to_lowercase()
            .collect::<String>()
            + chars.as_str();
        out.push_str(&format!(
            "    fun {name}(seq: Int, ts: String, data: {}, json: Json): JsonObject =\n        event(\"{}\", seq, ts, json.encodeToJsonElement(data))\n\n",
            kotlin_type(event.data), event.name,
        ));
    }
    out.push_str(concat!(
        "    private fun event(type: String, seq: Int, ts: String, data: JsonElement): JsonObject =\n",
        "        buildJsonObject {\n",
        "            put(\"jsonrpc\", \"2.0\")\n",
        "            put(\"method\", \"events\")\n",
        "            putJsonObject(\"params\") {\n",
        "                put(\"seq\", seq)\n",
        "                put(\"ts\", ts)\n",
        "                put(\"type\", type)\n",
        "                put(\"data\", data)\n",
        "            }\n",
        "        }\n",
        "}\n",
    ));
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn interface_and_dispatch_use_native_argument_lists() {
        let kotlin = generate();
        assert!(
            kotlin.contains("suspend fun appList(includeSystem: Boolean? = null): AppListResult")
        );
        assert!(kotlin.contains("suspend fun appLaunch(packageName: String, activity: String? = null, forceStop: Boolean? = null)"));
        assert!(kotlin.contains(
            "device.appLaunch(decoded.package_name, decoded.activity, decoded.force_stop)"
        ));
        assert!(kotlin.contains("json.decodeFromJsonElement<AppLaunchParams>(params)"));
        assert!(kotlin.contains("默认只返回带 LAUNCHER 入口的包。"));
        assert!(!kotlin.contains("suspend fun appList(params:"));
    }

    #[test]
    fn event_helpers_bind_names_and_data_types() {
        let kotlin = generate();
        assert!(kotlin.contains(
            "fun notificationPosted(seq: Int, ts: String, data: NotificationPostedData, json: Json)"
        ));
        assert!(
            kotlin.contains(
                "event(\"notification.posted\", seq, ts, json.encodeToJsonElement(data))"
            )
        );
        assert!(kotlin.contains("put(\"method\", \"events\")"));
        assert!(!kotlin.contains("put(\"id\""));
    }
}
