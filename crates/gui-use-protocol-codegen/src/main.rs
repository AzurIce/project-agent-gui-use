//! 从 `gui-use-protocol` 的方法注册表生成 Kotlin 接口、文档表格和机器可读清单。
//!
//! 用法：
//!   cargo run -p gui-use-protocol-codegen
//!   cargo run -p gui-use-protocol-codegen -- --check

use std::fs;
use std::path::{Path, PathBuf};

use gui_use_protocol::{METHODS, MethodSpec};

const KOTLIN_PATH: &str = "android/app/src/main/java/dev/azurice/guiuse/protocol/Methods.kt";
const REGISTRY_PATH: &str = "protocol/registry.json";
const DOCS_PATH: &str = "docs/protocol/generated.md";

fn main() {
    let check = std::env::args().any(|a| a == "--check");
    let root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .ancestors()
        .nth(2)
        .expect("repository root")
        .to_path_buf();

    let files = [
        (KOTLIN_PATH, kotlin()),
        (REGISTRY_PATH, registry()),
        (DOCS_PATH, docs()),
    ];

    if check {
        let mut stale = Vec::new();
        for (path, content) in &files {
            let full = root.join(path);
            match fs::read_to_string(&full) {
                Ok(existing) if existing == *content => {}
                _ => stale.push(*path),
            }
        }
        if stale.is_empty() {
            println!("protocol artifacts are up to date");
            return;
        }
        for path in stale {
            eprintln!("out of date: {path}");
        }
        std::process::exit(1);
    }

    for (path, content) in &files {
        let full = root.join(path);
        write_if_changed(&full, content);
        println!("wrote {}", full.display());
    }
}

fn write_if_changed(path: &PathBuf, content: &str) {
    if fs::read_to_string(path).ok().as_deref() == Some(content) {
        return;
    }
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).expect("create output directory");
    }
    fs::write(path, content).expect("write generated file");
}

fn pascal(ident: &str) -> String {
    ident
        .split('_')
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                Some(first) => first.to_uppercase().collect::<String>() + chars.as_str(),
                None => String::new(),
            }
        })
        .collect()
}

fn camel(ident: &str) -> String {
    let mut parts = ident.split('_');
    let mut out = parts.next().unwrap_or_default().to_string();
    for part in parts {
        out.push_str(&pascal(part));
    }
    out
}

fn upper_snake(ident: &str) -> String {
    ident.to_uppercase()
}

fn kotlin() -> String {
    let mut out = String::new();
    out.push_str("// Generated by gui-use-protocol-codegen. Do not edit by hand.\n");
    out.push_str("package dev.azurice.guiuse.protocol\n\n");
    out.push_str("import kotlinx.serialization.json.Json\n\n");

    out.push_str("object Methods {\n");
    for spec in METHODS {
        out.push_str(&format!(
            "    const val {} = \"{}\"\n",
            upper_snake(spec.ident),
            spec.name
        ));
    }
    out.push_str("}\n\n");

    for spec in METHODS {
        let base = pascal(spec.ident);
        out.push_str(&format!(
            "interface {base}Handler {{\n    suspend fun handle(params: {}): {}\n}}\n\n",
            spec.params, spec.result
        ));
    }

    out.push_str("interface Handlers {\n");
    for spec in METHODS {
        let base = pascal(spec.ident);
        out.push_str(&format!("    val {}: {base}Handler\n", camel(spec.ident)));
    }
    out.push_str("}\n\n");

    out.push_str("object ProtocolDispatch {\n");
    out.push_str("    suspend fun dispatch(method: String, params: String, json: Json, handlers: Handlers): String =\n");
    out.push_str("        when (method) {\n");
    for spec in METHODS {
        out.push_str(&format!(
            "            Methods.{} -> json.encodeToString(\n",
            upper_snake(spec.ident)
        ));
        out.push_str(&format!("                {}.serializer(),\n", spec.result));
        out.push_str(&format!(
            "                handlers.{}.handle(json.decodeFromString({}.serializer(), params)),\n",
            camel(spec.ident),
            spec.params
        ));
        out.push_str("            )\n");
    }
    out.push_str(
        "            else -> throw IllegalArgumentException(\"unknown method: $method\")\n",
    );
    out.push_str("        }\n");
    out.push_str("}\n");
    out
}

fn registry() -> String {
    let methods: Vec<serde_json::Value> = METHODS
        .iter()
        .map(|spec: &MethodSpec| {
            serde_json::json!({
                "name": spec.name,
                "params": spec.params,
                "result": spec.result,
                "summary": spec.summary,
            })
        })
        .collect();
    let doc = serde_json::json!({
        "protocol": 1,
        "methods": methods,
    });
    let mut text = serde_json::to_string_pretty(&doc).expect("serialize registry");
    text.push('\n');
    text
}

fn docs() -> String {
    let mut out = String::new();
    out.push_str("# 方法索引\n\n");
    out.push_str("> 本页由 `just protocol` 生成，请勿手改。\n\n");
    out.push_str("| 方法 | 参数 | 返回 | 说明 |\n");
    out.push_str("| --- | --- | --- | --- |\n");
    for spec in METHODS {
        out.push_str(&format!(
            "| `{}` | `{}` | `{}` | {} |\n",
            spec.name, spec.params, spec.result, spec.summary
        ));
    }
    out
}
